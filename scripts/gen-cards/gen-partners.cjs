#!/usr/bin/env node
// scripts/gen-cards/gen-partners.cjs
// cards-data の全 partner.tsv を検証し、既存の生成 CardDef を参照する
// 集約 barrel src/cards/_generated/partners.ts を再生成する。
// 個別 CardDef は作成・上書きしない。手書き owner は _reuse へ登録されていることを要求する。
//
// spec: docs/superpowers/specs/2026-06-03-all-partners-generator-design.md
// 再実行: node scripts/gen-cards/gen-partners.cjs
//
// MVP (ct-d08 / ct-d11) と CT-P10 は手書き/reuse owner のためスキップ。

const fs = require('fs');
const path = require('path');
const { withCardsDataSnapshot } = require('../cards/official-api.cjs');

const ROOT = path.resolve(__dirname, '..', '..');
const DATA_DIR = path.resolve(process.env.CONAN_CARDS_DATA_DIR || path.join(ROOT, '.claude', 'specs', 'cards-data'));
const CARDS_DIR = path.join(ROOT, 'src', 'cards');
const REUSE_INDEX_PATH = path.join(CARDS_DIR, '_reuse', 'index.ts');
// MVP と CT-P10 は手書き/reuse owner。generated barrel へ重複登録しない。
const SKIP_PKGS = new Set(['ct-d08', 'ct-d11', 'ct-p10']);

function parseTsvLines(text) {
  return text.split(/\r?\n/).filter((l) => l.length > 0);
}

function partnerAssistFileThreshold(effect) {
  const normalized = effect.trim().replaceAll('<br>', '\\n');
  if (!normalized) return undefined;
  const match = normalized.match(/^【解決編】【事件解決】【スリープ】：自分の証拠が事件レベルの数以上ある場合、ゲームに勝利する。\\n【アシスト】【スリープ】：FILEエリアに移動する。自分のFILEエリアにカードが(\d+)枚以上ある場合、事件を解決編にする。$/u);
  if (!match) throw new Error(`unrecognized partner assist text: ${effect}`);
  const threshold = Number(match[1]);
  if (!Number.isSafeInteger(threshold) || threshold < 1) throw new Error(`invalid partner assist FILE threshold: ${match[1]}`);
  return threshold === 7 ? undefined : threshold;
}

function main() {
  const reuseIndex = fs.readFileSync(REUSE_INDEX_PATH, 'utf8');
  const pkgs = fs
    .readdirSync(DATA_DIR, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .filter((name) => !SKIP_PKGS.has(name))
    .filter((name) => fs.existsSync(path.join(DATA_DIR, name, 'partner.tsv')))
    .sort();

  /** @type {{cardNum:string, pkg:string}[]} */
  const generated = [];
  const seenIds = new Set();
  let generatedCount = 0;
  const perPkg = {};

  for (const pkg of pkgs) {
    const tsvPath = path.join(DATA_DIR, pkg, 'partner.tsv');
    const lines = parseTsvLines(fs.readFileSync(tsvPath, 'utf8'));
    const header = lines[0].split('\t');
    const col = (name) => header.indexOf(name);
    const iNum = col('cardNum');
    const iEffect = col('effect');

    const outDir = path.join(CARDS_DIR, pkg);

    let pkgCount = 0;
    for (let r = 1; r < lines.length; r++) {
      const c = lines[r].split('\t');
      const cardNum = c[iNum];
      if (!cardNum) continue;
      if (seenIds.has(cardNum)) {
        throw new Error(`duplicate cardNum across packages: ${cardNum} (${pkg})`);
      }
      seenIds.add(cardNum);
      const threshold = partnerAssistFileThreshold(c[iEffect] || '');
      const outputPath = path.join(outDir, `${cardNum}.ts`);
      if (!fs.existsSync(outputPath)) {
        throw new Error(`partner definition is missing: ${pkg}/${cardNum}`);
      }
      const hasManualOwner = !fs.readFileSync(outputPath, 'utf8').includes('auto-generated by scripts/gen-cards/gen-partners.cjs');
      if (hasManualOwner) {
        if (!reuseIndex.includes(`../${pkg}/${cardNum}.js`)) {
          throw new Error(`manual partner must be owned by _reuse: ${pkg}/${cardNum}`);
        }
        continue;
      }
      generated.push({ cardNum, pkg, threshold });
      generatedCount++;
      pkgCount++;
    }
    perPkg[pkg] = pkgCount;
  }

  // 集約 barrel
  const genDir = path.join(CARDS_DIR, '_generated');
  if (!fs.existsSync(genDir)) fs.mkdirSync(genDir, { recursive: true });
  const imports = generated
    .map((g) => `import { ${g.cardNum} } from '../${g.pkg}/${g.cardNum}.js';`)
    .join('\n');
  const arrItems = generated.map((g) => `{ ...${g.cardNum}, standardPartnerActions: true${g.threshold === undefined ? '' : `, partnerAssistFileThreshold: ${g.threshold}`} }`);
  // 80 文字程度で改行しつつ配列展開
  const arrLines = [];
  for (let i = 0; i < arrItems.length; i += 8) {
    arrLines.push('  ' + arrItems.slice(i, i + 8).join(', ') + ',');
  }
  const barrel = `// cards/_generated/partners — auto-generated by scripts/gen-cards/gen-partners.cjs
// ${generated.length} 件の非MVP partner CardDef (abilities:[] stub) を集約。手で編集しない。
import type { CardDef } from '@/engine/types';

${imports}

export const GENERATED_PARTNERS: CardDef[] = [
${arrLines.join('\n')}
];
`;
  fs.writeFileSync(path.join(genDir, 'partners.ts'), barrel, 'utf8');

  console.log(`[gen-partners] indexed ${generatedCount} generated partner CardDefs across ${pkgs.length} packages:`);
  for (const pkg of pkgs) console.log(`  ${pkg}: ${perPkg[pkg]}`);
  console.log(`[gen-partners] barrel: src/cards/_generated/partners.ts (${generated.length} cards)`);
}

withCardsDataSnapshot({ baseDir: DATA_DIR, read: () => main() });
