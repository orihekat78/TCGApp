#!/usr/bin/env node
// scripts/gen-cards/gen-partners.cjs
// cards-data の全 partner.tsv (~280枚) のうち未作成 (非MVP 17パッケージ) を
// src/cards/<pkg>/<cardNum>.ts (CardDef, abilities:[] stub) として生成し、
// 集約 barrel src/cards/_generated/partners.ts を生成する。
//
// spec: docs/superpowers/specs/2026-06-03-all-partners-generator-design.md
// 再実行: node scripts/gen-cards/gen-partners.cjs
//
// MVP (ct-d08 / ct-d11) は手書き済のためスキップ。

const fs = require('fs');
const path = require('path');
const { withCardsDataSnapshot } = require('../cards/official-api.cjs');

const ROOT = path.resolve(__dirname, '..', '..');
const DATA_DIR = path.resolve(process.env.CONAN_CARDS_DATA_DIR || path.join(ROOT, '.claude', 'specs', 'cards-data'));
const CARDS_DIR = path.join(ROOT, 'src', 'cards');
const SKIP_PKGS = new Set(['ct-d08', 'ct-d11']); // MVP は手書き済

// single-quote 文字列リテラル用 escape
function sq(s) {
  return "'" + String(s ?? '').replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
}

function parseTsvLines(text) {
  return text.split(/\r?\n/).filter((l) => l.length > 0);
}

function main() {
  const pkgs = fs
    .readdirSync(DATA_DIR, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .filter((name) => !SKIP_PKGS.has(name))
    .filter((name) => fs.existsSync(path.join(DATA_DIR, name, 'partner.tsv')))
    .sort();

  /** @type {{cardNum:string, pkg:string}[]} */
  const generated = [];
  const seenIds = new Set();
  let fileCount = 0;
  const perPkg = {};

  for (const pkg of pkgs) {
    const tsvPath = path.join(DATA_DIR, pkg, 'partner.tsv');
    const lines = parseTsvLines(fs.readFileSync(tsvPath, 'utf8'));
    const header = lines[0].split('\t');
    const col = (name) => header.indexOf(name);
    const iNum = col('cardNum');
    const iId = col('cardId');
    const iTitle = col('title');
    const iColor = col('color');
    const iLp = col('lp');
    const iRarity = col('rarity');
    const iImg = col('imagePath');

    const outDir = path.join(CARDS_DIR, pkg);
    if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });

    let pkgCount = 0;
    for (let r = 1; r < lines.length; r++) {
      const c = lines[r].split('\t');
      const cardNum = c[iNum];
      if (!cardNum) continue;
      if (seenIds.has(cardNum)) {
        throw new Error(`duplicate cardNum across packages: ${cardNum} (${pkg})`);
      }
      seenIds.add(cardNum);
      const cardId = c[iId] || '';
      const title = c[iTitle] || '';
      const color = c[iColor] || '';
      const lp = c[iLp] || '0';
      const rarity = c[iRarity] || '';
      const img = c[iImg] || '';

      const body = `// cards/${pkg}/${cardNum} ${title} (パートナー) — auto-generated by scripts/gen-cards/gen-partners.cjs
// 全パートナー共通能力 (アシスト / 事件解決) は engine 内蔵。個別能力は未実装 (TODO)。
import type { CardDef } from '@/engine/types';

export const ${cardNum}: CardDef = {
  id: ${sq(cardNum)},
  no: ${sq(`${cardId}/${cardNum}`)},
  kind: 'partner',
  names: [${sq(title)}],
  colors: [${sq(color)}],
  lp: ${Number(lp)},
  traits: [],
  rarity: ${sq(rarity)},
  imageUrl: ${sq(img)},
  abilities: [], // TODO: 個別能力 (ct-p05 / pr-01 の一部) は後日実装
  standardPartnerActions: true,
  ruleRefs: ['rules/01-victory-conditions.md', 'rules/13-keywords.md'],
};
`;
      fs.writeFileSync(path.join(outDir, `${cardNum}.ts`), body, 'utf8');
      generated.push({ cardNum, pkg });
      fileCount++;
      pkgCount++;
    }
    perPkg[pkg] = pkgCount;
  }

  // 集約 barrel
  const genDir = path.join(CARDS_DIR, '_generated');
  if (!fs.existsSync(genDir)) fs.mkdirSync(genDir, { recursive: true });
  const imports = generated
    .map((g) => `import { ${g.cardNum} } from '../${g.pkg}/${g.cardNum}.js';`)
    .join('\n');
  const arrItems = generated.map((g) => g.cardNum);
  // 80 文字程度で改行しつつ配列展開
  const arrLines = [];
  for (let i = 0; i < arrItems.length; i += 8) {
    arrLines.push('  ' + arrItems.slice(i, i + 8).join(', ') + ',');
  }
  const barrel = `// cards/_generated/partners — auto-generated by scripts/gen-cards/gen-partners.cjs
// ${generated.length} 件の非MVP partner CardDef (abilities:[] stub) を集約。手で編集しない。
import type { CardDef } from '@/engine/types';

${imports}

export const GENERATED_PARTNERS: CardDef[] = [
${arrLines.join('\n')}
];
`;
  fs.writeFileSync(path.join(genDir, 'partners.ts'), barrel, 'utf8');

  console.log(`[gen-partners] generated ${fileCount} partner CardDef files across ${pkgs.length} packages:`);
  for (const pkg of pkgs) console.log(`  ${pkg}: ${perPkg[pkg]}`);
  console.log(`[gen-partners] barrel: src/cards/_generated/partners.ts (${generated.length} cards)`);
}

withCardsDataSnapshot({ baseDir: DATA_DIR, read: () => main() });
