#!/usr/bin/env node

const fs = require('node:fs');
const path = require('node:path');
const { fetchAllCards, OFFICIAL_CARDS_URL } = require('./official-api.cjs');

const OUTPUT_PATH = path.join(
  __dirname,
  '..',
  '..',
  'meta-app',
  'src',
  'data',
  'caseDifficulties.generated.ts',
);
const INTEGER = /^\d+$/;

function parseDifficulty(value, field, cardNum) {
  if (typeof value !== 'string' || !INTEGER.test(value)) {
    throw new Error(`invalid ${field} for ${cardNum}: ${JSON.stringify(value)}`);
  }
  return Number(value);
}

function collectCaseDifficulties(cards) {
  const cases = [];
  for (const card of cards) {
    if (card?.type !== '事件') continue;
    const cardNum = card.card_num;
    if (typeof cardNum !== 'string' || cardNum.length === 0) {
      throw new Error(`official case card is missing card_num: ${JSON.stringify(card)}`);
    }
    if (typeof card.card_id !== 'string' || card.card_id.length === 0) {
      throw new Error(`official case card is missing card_id: ${cardNum}`);
    }
    cases.push(card);
  }

  const directPairsById = new Map();
  for (const card of cases) {
    if (card.difficulty_first == null && card.difficulty_second == null) continue;
    const first = parseDifficulty(card.difficulty_first, 'difficulty_first', card.card_num);
    const second = parseDifficulty(card.difficulty_second, 'difficulty_second', card.card_num);
    const pair = `${first}/${second}`;
    const pairs = directPairsById.get(card.card_id) ?? new Set();
    pairs.add(pair);
    directPairsById.set(card.card_id, pairs);
  }

  const entries = new Map();
  for (const card of cases) {
    if (entries.has(card.card_num)) throw new Error(`duplicate official case card number: ${card.card_num}`);
    let first;
    let second;
    if (card.difficulty_first == null && card.difficulty_second == null) {
      const pairs = directPairsById.get(card.card_id);
      if (!pairs || pairs.size !== 1) {
        throw new Error(`unresolvable official case difficulty: ${card.card_num} (${card.card_id})`);
      }
      [first, second] = [...pairs][0].split('/').map(Number);
    } else {
      first = parseDifficulty(card.difficulty_first, 'difficulty_first', card.card_num);
      second = parseDifficulty(card.difficulty_second, 'difficulty_second', card.card_num);
    }
    entries.set(card.card_num, { first, second });
  }
  return [...entries.entries()].sort(([left], [right]) => left.localeCompare(right));
}

function render(entries) {
  const lines = [
    '// Generated by scripts/cards/generate-case-difficulties.cjs. Do not edit manually.',
    `// Source: ${OFFICIAL_CARDS_URL}`,
    '',
    'export interface CaseDifficulty {',
    '  readonly first: number;',
    '  readonly second: number;',
    '}',
    '',
    'export const CASE_DIFFICULTIES_BY_NUM: Readonly<Record<string, CaseDifficulty>> = {',
  ];
  for (const [cardNum, difficulty] of entries) {
    lines.push(`  ${JSON.stringify(cardNum)}: { first: ${difficulty.first}, second: ${difficulty.second} },`);
  }
  lines.push('};', '');
  return lines.join('\n');
}

async function main() {
  const snapshot = await fetchAllCards();
  const entries = collectCaseDifficulties(snapshot.cards);
  fs.writeFileSync(OUTPUT_PATH, render(entries), 'utf8');
  process.stdout.write(`generated ${entries.length} case difficulties from ${snapshot.total} official cards\n`);
}

if (require.main === module) {
  main().catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
}

module.exports = { collectCaseDifficulties, parseDifficulty, render };
